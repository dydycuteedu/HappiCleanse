public class WorkingHour {
    private int idWorkingHour;
    private int hour;
    private double pricePerHour;

    public int getIdWorkingHour() {
        return idWorkingHour;
    }

    public void setIdWorkingHour(int idWorkingHour) {
        this.idWorkingHour = idWorkingHour;
    }

    public int getHour() {
        return hour;
    }

    public void setHour(int hour) {
        this.hour = hour;
    }

    public double getPricePerHour() {
        return pricePerHour;
    }

    public void setPricePerHour(double pricePerHour) {
        this.pricePerHour = pricePerHour;
    }
    
}
